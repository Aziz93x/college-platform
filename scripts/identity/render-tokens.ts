// Renders src/styles/tokens.css and src/styles/token-names.ts from the identity repo's digital
// tokens and the role mapping in identity.lock.json. Pure and deterministic; the output is already
// in Biome's format.

type Swatch = { row_from_top: number; column_from_left: number; hex: string };
export type DigitalTokens = { tokens: Record<string, Swatch> };

// A role maps to a swatch id from the digital tokens, or to "white" (the identity's surface).
export type TokenMapping = {
  from: string;
  hues: string[]; // palette column names, from the left
  light: Record<string, string>;
  dark: Record<string, string>;
  extra: Record<string, string>; // roles outside the palette, as hex, the same in both themes
};

const WHITE = "#ffffff";

const block = (selector: string, lines: string[]) =>
  [`${selector} {`, ...lines.map((line) => `  ${line}`), "}"].join("\n");

type Lock = { repo: string; commit: string; tokens: TokenMapping };

// The swatches by column, then row, each with its custom property name.
function paletteOf(source: DigitalTokens, hues: string[]) {
  return Object.entries(source.tokens)
    .map(([id, swatch]) => {
      const hue = hues[swatch.column_from_left - 1];
      if (!hue) throw new Error(`no hue name for the column of ${id}`);
      return { id, swatch, name: `--palette-${hue}-${swatch.row_from_top}` };
    })
    .sort(
      (a, b) =>
        a.swatch.column_from_left - b.swatch.column_from_left ||
        a.swatch.row_from_top - b.swatch.row_from_top,
    );
}

const rolesOf = ({ light, extra }: TokenMapping) => [
  ...Object.keys(light),
  ...Object.keys(extra),
];

export function renderTokens(source: DigitalTokens, lock: Lock): string {
  const { hues, light, dark, extra } = lock.tokens;
  const palette = paletteOf(source, hues);
  const names = new Map(palette.map(({ id, name }) => [id, name]));
  const roles = (mapping: Record<string, string>) =>
    Object.entries(mapping).map(([role, ref]) => {
      const name = names.get(ref);
      if (ref !== "white" && !name)
        throw new Error(`unknown swatch "${ref}" for --${role}`);
      return `--${role}: ${name ? `var(${name})` : WHITE};`;
    });

  const header = [
    `/* Generated by pnpm identity:sync from ${lock.repo} at commit ${lock.commit},`,
    `   ${lock.tokens.from}. Do not edit: change scripts/identity/identity.lock.json and run the sync.`,
    "   Palette steps are the source rows, 1 the darkest. Dark roles apply only under .dark. */",
  ].join("\n");
  return `${[
    header,
    block("@theme inline", [
      "--color-*: initial;",
      ...rolesOf(lock.tokens).map((role) => `--color-${role}: var(--${role});`),
    ]),
    block(":root", [
      ...palette.map(
        ({ name, swatch }) => `${name}: ${swatch.hex.toLowerCase()};`,
      ),
      ...roles(light),
      ...Object.entries(extra).map(
        ([role, hex]) => `--${role}: ${hex.toLowerCase()};`,
      ),
    ]),
    "@custom-variant dark (&:where(.dark, .dark *));",
    block(".dark", roles(dark)),
  ].join("\n\n")}\n`;
}

const list = (name: string, items: string[]) =>
  [
    `export const ${name} = [`,
    ...items.map((item) => `  "${item}",`),
    "] as const;",
  ].join("\n");

// The custom property names, for pages that show every token (/design). Dark roles have the same
// names, applied under .dark.
export function renderTokenNames(source: DigitalTokens, lock: Lock): string {
  return `${[
    [
      `// Generated by pnpm identity:sync from ${lock.repo} at commit ${lock.commit}.`,
      "// Do not edit: the custom properties of src/styles/tokens.css.",
    ].join("\n"),
    list(
      "paletteTokens",
      paletteOf(source, lock.tokens.hues).map(({ name }) => name),
    ),
    list(
      "roleTokens",
      rolesOf(lock.tokens).map((role) => `--${role}`),
    ),
  ].join("\n\n")}\n`;
}
